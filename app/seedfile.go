func luaStr(s string) string { return strconv.Quote(s) } // Go quoting is valid Lua for our ASCII paths

// luaValue renders decoded JSON as a Lua literal
func luaValue(v interface{}) string {
	switch x := v.(type) {
	case nil:
		return "nil"
	case bool:
		return strconv.FormatBool(x)
	case float64:
		return strconv.FormatFloat(x, 'g', -1, 64)
	case string:
		return luaStr(x)
	case []interface{}:
		parts := make([]string, len(x))
		for i, e := range x {
			parts[i] = luaValue(e)
		}
		return "{" + strings.Join(parts, ",") + "}"
	case map[string]interface{}:
		keys := make([]string, 0, len(x))
		for k := range x {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		parts := make([]string, 0, len(x))
		for _, k := range keys {
			parts = append(parts, "["+luaStr(k)+"]="+luaValue(x[k]))
		}
		return "{" + strings.Join(parts, ",") + "}"
	}
	return "nil"
}

// Spots whose look is just the item lying there; these show the new item's model.
// Vaults, baggage and supply chests are creatures/containers and keep their look.
var simpleSpot = map[string]bool{"figment": true, "psicard": true, "psimarker": true, "halfamind": true,
	"nugget": true, "bagtag": true, "supplykey": true, "scavenger": true}

// visualFor returns the drawing recipe to show at p.Loc, or nil to keep the original look.
func visualFor(p Placement) (vis []interface{}, scale, zoff float64) {
	if p.From == p.Loc || !simpleSpot[p.Loc.Cat] || len(p.From.Vis) == 0 {
		return nil, 0, 0
	}
	if p.Loc.Cat == "figment" && p.Reward.Cat == "figment" {
		return nil, 0, 0 // a figment counts at whatever spot you touch, so its art stays
	}
	switch p.From.Cat {
	case "vault", "baggage", "supplychest":
		return p.From.Vis, 0.35, 30 // a small walking safe / crying bag marks these rewards
	}
	return p.From.Vis, 0, 0
}

// WriteSeed writes the Lua seed table the mod loads, plus a spoiler log.
func WriteSeed(modDir string, slot int, gd *GameData, res *SeedResult) (seedPath, spoilerPath string, err error) {
	dir := filepath.Join(modDir, "seeds")
	if err = os.MkdirAll(dir, 0o755); err != nil {
		return
	}
	var b strings.Builder
	b.WriteString("-- PsychoRando seed. Generated by PsychoRando.exe; do not edit.\n")
	b.WriteString("local L = {}\n")
	fmt.Fprintf(&b, "local seed = { version = 1, seed = %s, slot = %d, created = %s,\n",
		luaStr(res.Options.Seed), slot, luaStr(res.Created.Format("2006-01-02 15:04:05")))

	// categories that are randomized
	b.WriteString("  cats = {")
	var cats []string
	for c, on := range res.Options.Categories {
		if on {
			cats = append(cats, c)
		}
	}
	sort.Strings(cats)
	for _, c := range cats {
		fmt.Fprintf(&b, " [%s] = true,", luaStr(c))
	}
	b.WriteString(" },\n")

	// item path -> category, so the mod can recognise an original reward arriving
	itemCat := map[string]string{}
	for _, l := range gd.Locations {
		for _, g := range l.Orig.Grants {
			if _, ok := itemCat[g.Path]; !ok {
				itemCat[g.Path] = l.Cat
			}
		}
	}
	for p := range gd.Items {
		up := strings.ToUpper(shortName(p))
		var c string
		switch {
		case strings.HasPrefix(up, "INV_VAULT_"):
			c = "vault"
		case strings.HasPrefix(up, "INV_SORTEDBAG_"):
			c = "baggage"
		case strings.HasPrefix(up, "INV_BAGTAG_"):
			c = "bagtag"
		case strings.HasPrefix(up, "SCAVHUNTITEM_"):
			c = "scavenger"
		case strings.HasPrefix(up, "INV_MIND_HP"):
			c = "halfamind"
		}
		if c != "" {
			if _, ok := itemCat[p]; !ok {
				itemCat[p] = c
			}
		}
	}
	b.WriteString("  itemCat = {\n")
	var ips []string
	for p := range itemCat {
		ips = append(ips, p)
	}
	sort.Strings(ips)
	for _, p := range ips {
		fmt.Fprintf(&b, "    [%s] = %s,\n", luaStr(p), luaStr(itemCat[p]))
	}
	hasActor := false
	for _, p := range res.Placements {
		if p.Loc.ID == "" {
			hasActor = true
		}
	}
	figParams := "nil"
	if gd.FigParams != nil {
		figParams = luaValue(map[string]interface{}(gd.FigParams))
	}
	startAt := "nil"
	if res.Options.StartMotherlobe {
		startAt = luaStr("motherlobe")
	}
	fmt.Fprintf(&b, "  },\n  hasActorLocs = %v,\n  figParams = %s,\n  startAt = %s,\n  locs = L,\n}\n", hasActor, figParams, startAt)

	// locations: one shared table per location, referenced from each alias
	for i, p := range res.Placements {
		fmt.Fprintf(&b, "do local e = { c = %s, label = %s, from = %s, give = {", luaStr(p.Loc.Cat), luaStr(p.Reward.Label), luaStr(p.From.Key))
		for _, g := range p.Reward.Grants {
			fmt.Fprintf(&b, " { %s, %d },", luaStr(g.Path), g.Amount)
		}
		b.WriteString(" }")
		if vis, sc, zo := visualFor(p); vis != nil {
			b.WriteString(", vis = " + luaValue(vis))
			if sc > 0 {
				fmt.Fprintf(&b, ", vscale = %g, voff = %g", sc, zo)
			}
		}
		b.WriteString(" }")
		for _, a := range p.Loc.Aliases {
			fmt.Fprintf(&b, " L[%s] = e", luaStr(a))
		}
		b.WriteString(" end\n")
		_ = i
	}
	b.WriteString("return seed\n")

	seedPath = filepath.Join(dir, fmt.Sprintf("slot_%d.lua", slot))
	tmp := seedPath + ".tmp"
	if err = os.WriteFile(tmp, []byte(b.String()), 0o644); err != nil {
		return
	}
	if err = os.Rename(tmp, seedPath); err != nil {
		return
	}
	gives := map[string]string{}
	for _, p := range res.Placements {
		gives[p.Loc.Key] = p.Reward.Label
	}
	if jb, jerr := json.Marshal(map[string]interface{}{"seed": res.Options.Seed, "gives": gives}); jerr == nil {
		_ = os.WriteFile(filepath.Join(dir, fmt.Sprintf("slot_%d.json", slot)), jb, 0o644)
	}
	spoilerPath = filepath.Join(dir, fmt.Sprintf("slot_%d_spoiler.txt", slot))
	err = os.WriteFile(spoilerPath, []byte(Spoiler(slot, res)), 0o644)
	return
}

func locDesc(l *Location) string {
	return fmt.Sprintf("%s — %s (%s)", LevelName(l.Level), catNames[l.Cat], l.Actor)
}

// Spoiler renders a human-readable log grouped by level.
func Spoiler(slot int, res *SeedResult) string {
	var b strings.Builder
	fmt.Fprintf(&b, "PsychoRando spoiler log\nSeed: %s\nSave slot: %d\nCreated: %s\n", res.Options.Seed, slot+1, res.Created.Format("2006-01-02 15:04"))
	var cats []string
	for c, on := range res.Options.Categories {
		if on {
			cats = append(cats, catNames[c])
		}
	}
	sort.Strings(cats)
	fmt.Fprintf(&b, "Randomized: %s\nScope: %s, figments: %s, logic: %v\n", strings.Join(cats, ", "), res.Options.Scope, res.Options.Figments, res.Options.Logic)
	fmt.Fprintf(&b, "Locations: %d (moved %d, %d to another level)\n", res.Stats["locations"], res.Stats["moved"], res.Stats["crossLevel"])
	if res.Options.StartMotherlobe {
		fmt.Fprintf(&b, "Starts at the Motherlobe; %d Loboto's Labyrinth spots left out\n", res.Stats["skippedIntro"])
	}
	b.WriteString("\n")

	byLevel := map[string][]Placement{}
	for _, p := range res.Placements {
		byLevel[p.Loc.Level] = append(byLevel[p.Loc.Level], p)
	}
	var levels []string
	for l := range byLevel {
		levels = append(levels, l)
	}
	sort.Strings(levels)

	// Non-figment rewards first: that's what people look for
	b.WriteString("=== Where everything went (excluding figment-to-figment) ===\n")
	for _, lv := range levels {
		ps := byLevel[lv]
		sort.Slice(ps, func(i, j int) bool {
			if ps[i].Loc.Cat != ps[j].Loc.Cat {
				return ps[i].Loc.Cat < ps[j].Loc.Cat
			}
			return ps[i].Loc.Actor < ps[j].Loc.Actor
		})
		header := false
		for _, p := range ps {
			if p.Loc.Cat == "figment" && p.Reward.Cat == "figment" {
				continue
			}
			if !header {
				fmt.Fprintf(&b, "\n[%s] %s\n", lv, LevelName(lv))
				header = true
			}
			fmt.Fprintf(&b, "  %-22s %-40s -> %s   (was in %s)\n", catNames[p.Loc.Cat], p.Loc.Actor, p.Reward.Label, LevelName(p.From.Level))
		}
	}
	b.WriteString("\n\n=== Item finder ===\n")
	type row struct{ item, where string }
	var rows []row
	for _, p := range res.Placements {
		if p.Reward.Cat == "figment" {
			continue
		}
		rows = append(rows, row{p.Reward.Label, locDesc(p.Loc)})
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].item < rows[j].item })
	for _, r := range rows {
		fmt.Fprintf(&b, "  %-40s %s\n", r.item, r.where)
	}
	return b.String()
}
